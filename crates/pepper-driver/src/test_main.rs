//! `pep-build --test`: the `main` a test build adds to the entry file.
//!
//! A test build defines the build option `TEST`, which keeps the `[Test]`
//! functions every other build drops (`passes::platform::keep`), loads the
//! runtime's `testing` module into every file, and appends to the entry
//! file's text a `main` that registers each of the file's `[Test]`
//! functions with a `TestRunner`:
//!
//! ```text
//! [TestMain]
//! main(args: String[]): int {
//!     var _pep_tests = TestRunner("math_test.pep");
//!     _pep_tests.add("adds", adds, 4);
//!     _pep_tests.add_should_panic("divides_by_zero", divides_by_zero, 9, "division by zero");
//!     return _pep_tests.run(args);
//! }
//! ```
//!
//! The text goes into the entry file itself, after its last line, so it
//! can name the file's private functions and every location before it
//! stays where it was. `[TestMain]` makes it replace the file's own `main`
//! (`passes::entry_point::lower_main_arguments`).
//!
//! Given several files of one folder, the build makes one program of them
//! all ([`test_program`]): each file gets an exported function that
//! registers its own tests (it can name its private ones), and a generated
//! entry file beside them imports every file and calls each one's from its
//! `main`. Each file keeps the scope it has in any program: the files of
//! a module's folder see each other's names (a `private` one excepted), and
//! other files see only what is exported.

use pepper_parser::ast::{Declaration, Expression, Literal};
use pepper_sema::passes::platform::{SHOULD_PANIC_ATTRIBUTE, TEST_ATTRIBUTE};
use pepper_sema::program::Root;

/// The module a test build loads into every file, which declares
/// `TestRunner` and `[TestMain]`.
pub const TESTING_MODULE: &str = "testing";

/// Append the test `main` to `root`'s text. A file that does not parse is
/// left as it is, for loading to report the error where it is.
pub fn add_test_main(root: &mut Root) {
    let Some(registrations) = registrations(&root.source) else {
        return;
    };
    let file = quoted(&root.path.to_string_lossy());
    if !root.source.ends_with('\n') {
        root.source.push('\n');
    }
    root.source.push_str(&format!(
        "\n# Added by pep-build --test: runs this file's [Test] functions.\n\
         [TestMain]\n\
         main(args: String[]): int {{\n\
         \x20   var _pep_tests = TestRunner({file});\n\
         {registrations}\
         \x20   return _pep_tests.run(args);\n\
         }}\n"
    ));
}

/// The name of the file the generated entry of a test build of several
/// files has, in their folder. Nothing is written there.
pub const ENTRY_FILE: &str = "_pep_test_main.pep";

/// The program a test build of several files makes: the generated entry
/// file, and each test file's text with the function that registers its
/// tests added (see the module comment). The files must share one folder.
/// A file that does not parse is left as it is, for loading to report the
/// error where it is.
pub fn test_program(files: &[std::path::PathBuf]) -> Result<(Root, Vec<(std::path::PathBuf, String)>), String> {
    let folder = files[0].parent().map(|p| p.to_path_buf()).unwrap_or_default();
    let mut sources = vec![];
    let mut imports = String::new();
    let mut calls = String::new();
    for (index, path) in files.iter().enumerate() {
        if path.parent().map(|p| p.to_path_buf()).unwrap_or_default() != folder {
            return Err(format!(
                "--test: {} is not in the folder of {}; the files of one test program share a folder",
                path.display(),
                files[0].display()
            ));
        }
        let mut source = std::fs::read_to_string(path).map_err(|e| format!("cannot read {}: {}", path.display(), e))?;
        let Some(stem) = path.file_stem().map(|s| s.to_string_lossy().into_owned()) else { continue };
        imports.push_str(&format!("import {};\n", quoted(&stem)));
        if let Some(registrations) = registrations(&source) {
            if !source.ends_with('\n') {
                source.push('\n');
            }
            source.push_str(&format!(
                "\n# Added by pep-build --test: registers this file's [Test] functions.\n\
                 export _pep_register_tests_{index}(_pep_tests: TestRunner) {{\n\
                 \x20   _pep_tests.from_file({file});\n\
                 {registrations}\
                 }}\n",
                file = quoted(&path.to_string_lossy())
            ));
            calls.push_str(&format!("    _pep_register_tests_{index}(_pep_tests);\n"));
        }
        sources.push((path.clone(), source));
    }
    let path = folder.join(ENTRY_FILE);
    let source = format!(
        "# Generated by pep-build --test: runs the [Test] functions of every file\n\
         # given.\n\
         {imports}\n\
         [TestMain]\n\
         main(args: String[]): int {{\n\
         \x20   var _pep_tests = TestRunner({folder});\n\
         {calls}\
         \x20   return _pep_tests.run(args);\n\
         }}\n",
        folder = quoted(&folder.to_string_lossy())
    );
    Ok((Root { name: path.to_string_lossy().into_owned(), source, path }, sources))
}

/// One `_pep_tests.add` (or `add_should_panic`) line per `[Test]` function
/// of `source`, or `None` when it does not parse.
fn registrations(source: &str) -> Option<String> {
    let module = pepper_parser::parser::parse_source_diag(source).ok()?;
    let mut registrations = String::new();
    for declaration in &module.declarations {
        let Declaration::Function(function) = declaration else {
            continue;
        };
        if !function.attributes.iter().any(|a| a.name() == Some(TEST_ATTRIBUTE)) {
            continue;
        }
        let line = source[..function.name_span.start].matches('\n').count() + 1;
        let name = &function.name;
        let should_panic = function.attributes.iter().find(|a| a.name() == Some(SHOULD_PANIC_ATTRIBUTE));
        match should_panic {
            None => registrations.push_str(&format!("    _pep_tests.add({}, {}, {});\n", quoted(name), name, line)),
            Some(attribute) => {
                // `[ShouldPanic("text")]` or `[ShouldPanic(message = "text")]`;
                // sema reports any other argument.
                let message = attribute
                    .arguments()
                    .into_iter()
                    .find_map(|argument| match argument.value {
                        Expression::Literal { value: Literal::String(text), .. } => Some(text.clone()),
                        _ => None,
                    })
                    .unwrap_or_default();
                registrations.push_str(&format!(
                    "    _pep_tests.add_should_panic({}, {}, {}, {});\n",
                    quoted(name),
                    name,
                    line,
                    quoted(&message)
                ));
            }
        }
    }
    Some(registrations)
}

/// `text` as a Pepper string literal.
fn quoted(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn with_main(source: &str) -> String {
        let mut root = Root { name: "t.pep".to_string(), source: source.to_string(), path: "t.pep".into() };
        add_test_main(&mut root);
        root.source
    }

    #[test]
    fn registers_each_test_with_its_line() {
        let text = with_main("[Test]\nfirst() {}\n\n[Test]\n[ShouldPanic(\"out of \\\"range\\\"\")]\nsecond() {}\n");
        assert!(text.contains("_pep_tests.add(\"first\", first, 2);"), "{}", text);
        assert!(text.contains("_pep_tests.add_should_panic(\"second\", second, 6, \"out of \\\"range\\\"\");"), "{}", text);
        assert!(text.contains("TestRunner(\"t.pep\")"), "{}", text);
    }

    #[test]
    fn leaves_a_file_that_does_not_parse() {
        assert_eq!(with_main("main( {"), "main( {");
    }
}
